        ALTER TABLE administrador ADD CONSTRAINT uq_administrador_usuario UNIQUE (usuario);
    END IF;
    IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conname = 'pk_tabla_reserva') THEN
        ALTER TABLE tabla_reserva ADD CONSTRAINT pk_tabla_reserva PRIMARY KEY (identificador);
    END IF;
    IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conname = 'pk_mesa') THEN
        ALTER TABLE mesa ADD CONSTRAINT pk_mesa PRIMARY KEY (identificador);
    END IF;
    IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conname = 'uq_mesa_numero') THEN
        ALTER TABLE mesa ADD CONSTRAINT uq_mesa_numero UNIQUE (numero_mesa);
    END IF;
    IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conname = 'pk_plato') THEN
        ALTER TABLE plato ADD CONSTRAINT pk_plato PRIMARY KEY (identificador);
    END IF;
    IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conname = 'pk_evento') THEN
        ALTER TABLE evento ADD CONSTRAINT pk_evento PRIMARY KEY (identificador);
    END IF;
    IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conname = 'pk_promocion') THEN
        ALTER TABLE promocion ADD CONSTRAINT pk_promocion PRIMARY KEY (identificador);
    END IF;
    IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conname = 'chk_tabla_reserva_numero_mesa') THEN
        ALTER TABLE tabla_reserva ADD CONSTRAINT chk_tabla_reserva_numero_mesa CHECK (numero_mesa > 0);
    END IF;
    IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conname = 'chk_tabla_reserva_cantidad') THEN
        ALTER TABLE tabla_reserva ADD CONSTRAINT chk_tabla_reserva_cantidad CHECK (cantidad_personas > 0);
    END IF;
    IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conname = 'chk_tabla_reserva_estado') THEN
        ALTER TABLE tabla_reserva ADD CONSTRAINT chk_tabla_reserva_estado CHECK (estado_pedido IN ('Disponible', 'Cancelado'));
    END IF;
    IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conname = 'fk_tabla_reserva_mesa') THEN
        ALTER TABLE tabla_reserva ADD CONSTRAINT fk_tabla_reserva_mesa FOREIGN KEY (numero_mesa) REFERENCES mesa (numero_mesa);
    END IF;
END $$;

