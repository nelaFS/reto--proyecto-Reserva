ALTER TABLE administrador
    ALTER COLUMN usuario TYPE VARCHAR(15),
    ALTER COLUMN usuario SET NOT NULL,
    ALTER COLUMN contrasena TYPE VARCHAR(60),
    ALTER COLUMN contrasena SET NOT NULL;

ALTER TABLE tabla_reserva
    ALTER COLUMN nombre_cliente SET NOT NULL,
    ALTER COLUMN numero_cliente SET NOT NULL,
    ALTER COLUMN estado_pedido SET NOT NULL,
    ALTER COLUMN numero_mesa SET NOT NULL,
    ALTER COLUMN cantidad_personas SET NOT NULL,
    ALTER COLUMN fecha_reserva SET DEFAULT CURRENT_TIMESTAMP,
    ALTER COLUMN fecha_reserva SET NOT NULL;

ALTER TABLE mesa
    ALTER COLUMN numero_mesa SET NOT NULL,
    ALTER COLUMN capacidad SET NOT NULL,
    ALTER COLUMN estado SET NOT NULL;

ALTER TABLE plato
    ALTER COLUMN nombre SET NOT NULL,
    ALTER COLUMN descripcion SET NOT NULL,
    ALTER COLUMN precio SET NOT NULL,
    ALTER COLUMN categoria SET NOT NULL,
    ALTER COLUMN disponible SET NOT NULL;

ALTER TABLE evento
    ALTER COLUMN nombre SET NOT NULL,
    ALTER COLUMN descripcion SET NOT NULL,
    ALTER COLUMN fecha SET NOT NULL,
    ALTER COLUMN hora SET NOT NULL,
    ALTER COLUMN estado SET NOT NULL;

ALTER TABLE promocion
    ALTER COLUMN titulo SET NOT NULL,
    ALTER COLUMN descripcion SET NOT NULL,
    ALTER COLUMN descuento SET NOT NULL,
    ALTER COLUMN fecha_inicio SET NOT NULL,
    ALTER COLUMN fecha_fin SET NOT NULL,
    ALTER COLUMN estado SET NOT NULL;

DO $$
BEGIN
    IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conname = 'pk_administrador') THEN
        ALTER TABLE administrador ADD CONSTRAINT pk_administrador PRIMARY KEY (identificador);
    END IF;
